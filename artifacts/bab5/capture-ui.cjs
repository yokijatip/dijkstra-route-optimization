const {chromium} = require('playwright-core');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1600,height:1100},deviceScaleFactor:1});
 const results=[];
 await page.goto('http://127.0.0.1:3000',{waitUntil:'domcontentloaded'});
 await page.locator('#simulator select').first().waitFor();
 await page.waitForFunction(()=>document.querySelector('#simulator select')?.options.length>=3);
 await page.getByRole('button',{name:'Run shortest path',exact:true}).waitFor();
 await page.locator('#simulator select').nth(1).selectOption('soreang');
 await page.locator('#simulator select').nth(2).selectOption('baleendah');
 await page.getByRole('button',{name:'Run shortest path',exact:true}).click();
 await page.getByText('✓ Correctness matched',{exact:true}).waitFor();
 results.push({test:'UI comparison on small-demo',passed:true});
 await page.locator('#comparison').screenshot({path:'artifacts/bab5/implementasi-comparison-demo.png'});
 await page.locator('#simulator select').nth(2).selectOption('soreang');
 await page.getByRole('button',{name:'Run shortest path',exact:true}).click();
 await page.getByText('Titik awal dan tujuan harus berbeda untuk simulasi ini.',{exact:true}).waitFor();
 results.push({test:'UI rejects identical source and destination',passed:true});
 await page.locator('#benchmark input').nth(0).fill('2');
 await page.locator('#benchmark input').nth(1).fill('0');
 await page.locator('#benchmark input').nth(2).fill('1');
 await page.getByRole('button',{name:'Run benchmark',exact:true}).click();
 await page.locator('#benchmark').getByText('Correctness matched',{exact:true}).waitFor();
 await page.locator('#history button').first().waitFor();
 results.push({test:'UI benchmark on small-demo (2 cases, 1 repeat, 0 warmup)',passed:true});
 const detailResponse=page.waitForResponse(r=>r.url().includes('/api/benchmarks/') && r.request().method()==='GET');
 await page.locator('#history button').first().click();
 if((await detailResponse).status()!==200) throw Error('History detail failed');
 results.push({test:'UI history detail request',passed:true});
 await page.locator('#benchmark').screenshot({path:'artifacts/bab5/implementasi-benchmark-demo.png'});
 await page.locator('#history').screenshot({path:'artifacts/bab5/implementasi-history-demo.png'});
 const link=page.getByRole('link',{name:'Download CSV',exact:true});
 const href=await link.getAttribute('href');
 const csv=await page.request.get(href);
 if(csv.status()!==200 || !(await csv.text()).includes('executionTimeNs')) throw Error('CSV export failed');
 results.push({test:'UI export link returns CSV',passed:true});
 await page.locator('#simulator select').first().selectOption('kota-bandung-osm-drive');
 await page.waitForFunction(()=>document.querySelectorAll('#simulator select')[1]?.options.length===27172);
 await page.locator('#simulator select').nth(1).selectOption('8123304877');
 await page.locator('#simulator select').nth(2).selectOption('2477129890');
 await page.getByRole('button',{name:/^optimized$/i}).click();
 const routeResponse=page.waitForResponse(r=>r.url().endsWith('/api/routes/optimized') && r.request().method()==='POST');
 await page.getByRole('button',{name:'Run shortest path',exact:true}).click();
 const route=await (await routeResponse).json();
 if(route.status!=='success') throw Error('Bandung optimized route failed');
 fs.writeFileSync('artifacts/bab5/ui-bandung-route.json',JSON.stringify(route,null,2));
 await page.locator('#simulator').screenshot({path:'artifacts/bab5/implementasi-simulator-bandung.png'});
 results.push({test:'UI loads Bandung graph and calculates optimized route',passed:true});
 fs.writeFileSync('artifacts/bab5/ui-tests.json',JSON.stringify(results,null,2));
 await browser.close();
 console.log(JSON.stringify(results));
})().catch(e=>{console.error(e);process.exit(1)});
